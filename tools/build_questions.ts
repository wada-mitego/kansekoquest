// ---- 追加問題（Web検索で出典を確認できた事実だけを素材にしたオリジナル問題）
function add(
  id: string,
  genre: string,
  question: string,
  correct: string[],
  wrong: string[],
  explanation: string,
  ref: string,
  note = '',
) {
  const texts = [...correct, ...wrong];
  out.push({
    id,
    genre,
    format: correct.length > 1 ? 'multiple' : 'single',
    question,
    choices: texts.map((t, i) => ({ id: IDS[i], text: t })),
    correctAnswerIds: correct.map((_, i) => IDS[i]),
    explanation,
    sourceYear: null,
    sourceExam: EXAM,
    sourceQuestionNo: null,
    sourceReference: ref,
    checkedAt: CHECKED,
    verificationStatus: 'verified',
    rightsStatus: 'original',
    revisionNotes: note,
  });
}

